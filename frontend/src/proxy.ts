import { type NextRequest, NextResponse } from "next/server";

/**
 * Content-Security-Policy with a fresh nonce per request (Next.js CSP guide, node_modules/next/dist/docs;
 * pre-deploy checklist, ADR-0042). Scripts run only with the nonce ('strict-dynamic'); styles allow inline
 * attributes because the coverage bar sets widths with `style`; images allow https because outlet photos are
 * hotlinked from the outlets (ADR-0034); the browser talks to the API origin directly.
 */
export function proxy(request: NextRequest) {
  const nonce = Buffer.from(crypto.randomUUID()).toString("base64");
  const dev = process.env.NODE_ENV === "development";
  const api = new URL(
    process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8000",
  ).origin;
  const csp = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${dev ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' https: data: blob:",
    "font-src 'self'",
    `connect-src 'self' ${api}`,
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(dev ? [] : ["upgrade-insecure-requests"]),
  ].join("; ");

  const requestHeaders = new Headers(request.headers);
  requestHeaders.set("x-nonce", nonce);
  requestHeaders.set("Content-Security-Policy", csp);
  const response = NextResponse.next({ request: { headers: requestHeaders } });
  response.headers.set("Content-Security-Policy", csp);
  return response;
}

export const config = {
  matcher: [
    {
      source:
        "/((?!api|_next/static|_next/image|favicon.ico|mockServiceWorker.js).*)",
      missing: [
        { type: "header", key: "next-router-prefetch" },
        { type: "header", key: "purpose", value: "prefetch" },
      ],
    },
  ],
};
